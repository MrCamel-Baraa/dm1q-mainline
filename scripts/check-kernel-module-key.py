#!/usr/bin/env python3
"""Does the kernel in a boot.img accept the modules that are inside the pmOS rootfs?

Background (docs/07-wlan-bringup.md, "ROOT CAUSE FOUND 2026-10-01"): the pmaports
mainline config signs every module with a *per-build random* key (MODULE_SIG_ALL,
certs/signing_key.pem is generated at build time) and, unless the dm1q fragment
overrides it, forces kernel lockdown (LOCK_DOWN_KERNEL_FORCE_INTEGRITY). This project
rebuilds the kernel often but builds the rootfs (and the /lib/modules inside it) once,
so after any rebuild the kernel's key no longer matches the rootfs' modules. With
lockdown forced, EVERY module is then refused ("Lockdown: modprobe: unsigned module
loading is restricted") -- no PCIe PHY, no pwrseq, nothing -- and the symptom looks like
a devicetree or PCIe-controller bug. With lockdown off the modules still load, tainted.

This script reads both sides and compares:
  * the signing certificate embedded in the kernel inside --boot  (serial, SKID)
  * the signer key id of a module inside the rootfs (--rootfs image, or --modules-dir)

Usage:
  scripts/check-kernel-module-key.py --boot <boot.img> --rootfs <pmos-userdata.img>
  scripts/check-kernel-module-key.py --boot <boot.img> --modules-dir <dir with usr/lib/modules>

Needs: openssl, modinfo (kmod, zstd support), debugfs (e2fsprogs; only for --rootfs).
Exit status: 0 = match, 1 = mismatch, 2 = could not determine.
"""
import argparse
import os
import re
import struct
import subprocess
import sys
import tempfile
import zlib

MARKER = b"Build time autogenerated kernel key"
PROBE_MODULE = "kernel/drivers/phy/qualcomm/phy-qcom-qmp-pcie.ko.zst"


def kernel_from_boot(path):
    with open(path, "rb") as f:
        hdr = f.read(4096)
        if hdr[:8] != b"ANDROID!":
            raise SystemExit("%s: not an Android boot image" % path)
        ksize = struct.unpack("<I", hdr[8:12])[0]
        f.seek(4096)
        k = f.read(ksize)
    if k[:2] == b"\x1f\x8b":                    # Image.gz-dtb: the DTB trails the gzip stream
        k = zlib.decompressobj(31).decompress(k)
    return k


def embedded_cert(kernel):
    """Find the DER certificate containing the autogenerated-key marker."""
    pos = 0
    while True:
        m = kernel.find(MARKER, pos)
        if m < 0:
            return None
        pos = m + 1
        for s in range(m - 3, max(0, m - 700), -1):
            if kernel[s] == 0x30 and kernel[s + 1] == 0x82:
                length = int.from_bytes(kernel[s + 2:s + 4], "big")
                if s < m < s + 4 + length and length < 4000:
                    der = kernel[s:s + 4 + length]
                    with tempfile.NamedTemporaryFile(delete=False) as t:
                        t.write(der)
                        name = t.name
                    r = subprocess.run(
                        ["openssl", "x509", "-inform", "der", "-in", name, "-noout",
                         "-serial", "-ext", "subjectKeyIdentifier"],
                        capture_output=True, text=True)
                    os.unlink(name)
                    if r.returncode == 0:
                        serial = re.search(r"serial=([0-9A-Fa-f]+)", r.stdout).group(1)
                        skid = re.search(r"([0-9A-F]{2}(?::[0-9A-F]{2}){19})", r.stdout)
                        return norm(serial), (skid.group(1) if skid else "?")


def norm(hexstr):
    return hexstr.replace(":", "").upper().lstrip("0")


def gpt_partitions(path):
    """Parse a GPT with either 4096- or 512-byte sectors (UFS userdata images use 4096)."""
    with open(path, "rb") as f:
        for ss in (4096, 512):
            f.seek(ss)
            h = f.read(92)
            if h[:8] != b"EFI PART":
                continue
            ent_lba, n, esz = struct.unpack("<QII", h[72:88])
            f.seek(ent_lba * ss)
            parts = []
            for _ in range(n):
                e = f.read(esz)
                if e[:16] == b"\0" * 16:
                    continue
                first, last = struct.unpack("<QQ", e[32:48])
                parts.append((first * ss, (last - first + 1) * ss))
            return parts
    raise SystemExit("%s: no GPT found" % path)


def module_from_rootfs_image(path):
    parts = gpt_partitions(path)
    off, _ = max(parts, key=lambda p: p[1])         # the root partition is the big one
    dev = "%s?offset=%d" % (path, off)
    ls = subprocess.run(["debugfs", "-R", "ls -p /usr/lib/modules", dev],
                        capture_output=True, text=True).stdout
    rels = [x.split("/")[5] for x in ls.splitlines() if x.count("/") >= 6 and x.split("/")[5][:1].isdigit()]
    if not rels:
        raise SystemExit("could not find /usr/lib/modules/<release> in %s" % path)
    out = tempfile.mkdtemp()
    dst = os.path.join(out, "probe.ko.zst")
    subprocess.run(["debugfs", "-R", "dump /usr/lib/modules/%s/%s %s" % (rels[0], PROBE_MODULE, dst), dev],
                   capture_output=True, text=True)
    if not os.path.exists(dst):
        raise SystemExit("probe module %s not found in rootfs" % PROBE_MODULE)
    return dst, rels[0]


def module_from_dir(d):
    for root, _, files in os.walk(d):
        for fn in files:
            if fn.startswith("phy-qcom-qmp-pcie.ko"):
                p = os.path.join(root, fn)
                m = re.search(r"/modules/([^/]+)/", p)
                return p, (m.group(1) if m else "?")
    raise SystemExit("no phy-qcom-qmp-pcie module under %s" % d)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--boot", required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--rootfs", help="pmos-userdata.img (GPT, root = largest partition)")
    g.add_argument("--modules-dir", help="directory containing an extracted usr/lib/modules tree")
    a = ap.parse_args()

    cert = embedded_cert(kernel_from_boot(a.boot))
    if not cert:
        print("could not find an autogenerated module-signing cert in the kernel of", a.boot)
        return 2
    kserial, kskid = cert

    if a.rootfs:
        mod, rel = module_from_rootfs_image(a.rootfs)
    else:
        mod, rel = module_from_dir(a.modules_dir)
    r = subprocess.run(["modinfo", "-F", "sig_key", mod], capture_output=True, text=True)
    sig_key = r.stdout.strip()
    if not sig_key:
        print("module %s carries no signature (modinfo sig_key empty)" % mod)
        return 2
    msig = norm(sig_key)

    print("kernel   (%s)" % a.boot)
    print("   embedded module-signing cert: serial %s  (SKID %s)" % (kserial, kskid))
    print("rootfs   (%s, modules for %s)" % (a.rootfs or a.modules_dir, rel))
    print("   %s signed by key serial: %s" % (os.path.basename(PROBE_MODULE).replace(".zst", ""), sig_key))
    if kserial == msig:
        print("\nMATCH: this kernel trusts the rootfs' modules.")
        return 0
    print("\nMISMATCH: the rootfs' modules were signed by a different build's key.")
    print("  - kernel built with LOCK_DOWN_KERNEL_FORCE_INTEGRITY (pmaports default): ALL modules are")
    print("    refused ('Lockdown: ... unsigned module loading is restricted') -> no PCIe PHY, no pwrseq.")
    print("  - kernel built with LOCK_DOWN_KERNEL_FORCE_NONE (dm1q fragment, r4+): modules load, tainted")
    print("    ('module verification failed: signature and/or required key missing').")
    print("  Either way, refresh the rootfs' modules from the kernel package you booted when the")
    print("  kernel config or sources changed (no MODVERSIONS here, so nothing else guards the ABI).")
    return 1


if __name__ == "__main__":
    sys.exit(main())
