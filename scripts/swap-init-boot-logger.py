#!/usr/bin/env python3
"""Swap ONLY /dtbo-logger.sh inside an existing init_boot image; every other cpio entry stays byte-identical.

Why: kernel/initramfs/dtbo-logger.sh lives in the pmOS stage-1 initramfs (init_boot). The pmOS initramfs
that scripts/make-boot-images.sh --initramfs consumes is regenerated by pmbootstrap on the phone, so
rebuilding from it would also pick up unrelated changes. This takes the image that is actually flashed
(docs/06: _scratch/init_boot_pmos_v2.img, sha256 35ea9693..) and changes exactly one file.

Usage: scripts/swap-init-boot-logger.py --in <init_boot.img> --logger <dtbo-logger.sh> --out <new init_boot.img>
Same container recipe as make-boot-images.sh: legacy LZ4 ramdisk (lz4 -l -9), mkbootimg header v4,
os_version 16.0.0 / patch level 2026-07, AVB hash footer (Algorithm NONE) for the 8 MiB partition.
Nothing here flashes anything. Needs unpack_bootimg, mkbootimg, avbtool, lz4 on PATH.
"""
import argparse, hashlib, os, subprocess, sys, tempfile

INIT_BOOT_SIZE = 8388608


def run(*a, **kw):
    return subprocess.run(a, check=True, **kw)


def parse_newc(buf):
    """-> (entries, tail). entry = dict(hdr fields as ints, name, data). Stops after TRAILER!!!."""
    off, entries = 0, []
    names = ("ino", "mode", "uid", "gid", "nlink", "mtime", "filesize", "devmajor", "devminor",
             "rdevmajor", "rdevminor", "namesize", "check")
    while True:
        if buf[off:off + 6] != b"070701":
            sys.exit(f"cpio: bad magic at {off}: {buf[off:off+6]!r}")
        f = {n: int(buf[off + 6 + 8 * i: off + 14 + 8 * i], 16) for i, n in enumerate(names)}
        p = off + 110
        name = buf[p:p + f["namesize"] - 1].decode()
        p += f["namesize"]; p = (p + 3) & ~3
        data = buf[p:p + f["filesize"]]
        p += f["filesize"]; p = (p + 3) & ~3
        entries.append(dict(f, name=name, data=data))
        off = p
        if name == "TRAILER!!!":
            return entries, buf[off:]


def build_newc(entries, tail):
    out = bytearray()
    for e in entries:
        name = e["name"].encode() + b"\0"
        hdr = b"070701" + b"".join(b"%08X" % v for v in (
            e["ino"], e["mode"], e["uid"], e["gid"], e["nlink"], e["mtime"], len(e["data"]),
            e["devmajor"], e["devminor"], e["rdevmajor"], e["rdevminor"], len(name), e["check"]))
        out += hdr + name
        out += b"\0" * (-len(out) % 4)
        out += e["data"]
        out += b"\0" * (-len(out) % 4)
    return bytes(out) + tail


def unpack(img, d):
    os.makedirs(d, exist_ok=True)
    txt = run("unpack_bootimg", "--boot_img", img, "--out", d, capture_output=True, text=True).stdout
    cpio = subprocess.run(["lz4", "-d", "-c", os.path.join(d, "ramdisk")], check=True, capture_output=True).stdout
    return txt, cpio


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", required=True)
    ap.add_argument("--logger", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    for t in ("unpack_bootimg", "mkbootimg", "avbtool", "lz4"):
        if subprocess.run(["which", t], capture_output=True).returncode:
            sys.exit(f"need {t} on PATH")
    logger = open(a.logger, "rb").read()
    W = tempfile.mkdtemp(prefix="swap-logger-")

    txt, cpio = unpack(a.inp, os.path.join(W, "old"))
    print("input unpack:", " | ".join(l for l in txt.splitlines() if "version" in l or "level" in l or "ramdisk size" in l))
    entries, tail = parse_newc(cpio)
    hits = [e for e in entries if e["name"] in ("dtbo-logger.sh", "./dtbo-logger.sh")]
    if len(hits) != 1:
        sys.exit(f"expected exactly one dtbo-logger.sh entry, found {len(hits)}")
    old = hits[0]["data"]
    print(f"entries: {len(entries)}; dtbo-logger.sh {len(old)} -> {len(logger)} bytes")
    if old == logger:
        print("logger already identical; nothing to change")
    hits[0]["data"] = logger
    new_cpio = build_newc(entries, tail)

    rd = os.path.join(W, "ramdisk.lz4")
    open(os.path.join(W, "new.cpio"), "wb").write(new_cpio)
    run("lz4", "-l", "-9", "-q", "-f", os.path.join(W, "new.cpio"), rd)
    run("mkbootimg", "--header_version", "4", "--ramdisk", rd, "--os_version", "16.0.0",
        "--os_patch_level", "2026-07", "--output", a.out)
    run("avbtool", "add_hash_footer", "--image", a.out, "--partition_size", str(INIT_BOOT_SIZE),
        "--partition_name", "init_boot", "--algorithm", "NONE")
    run("avbtool", "verify_image", "--image", a.out, stdout=subprocess.DEVNULL)
    print("AVB footer OK")

    # verification: unpack the result, every entry except the logger identical, logger == the given file
    txt2, cpio2 = unpack(a.out, os.path.join(W, "new"))
    e2, tail2 = parse_newc(cpio2)
    assert [e["name"] for e in e2] == [e["name"] for e in entries], "entry order/names changed"
    changed = [e["name"] for e, o in zip(e2, parse_newc(cpio)[0])
               if any(e[k] != o[k] for k in e if k != "data") or e["data"] != o["data"]]
    assert changed == [hits[0]["name"]], f"unexpected changes: {changed}"
    assert [e for e in e2 if e["name"] == hits[0]["name"]][0]["data"] == logger
    assert tail2 == tail, "cpio tail changed"
    hdr_old = [l for l in txt.splitlines() if l.startswith(("boot magic", "header version", "os version", "os patch level"))]
    hdr_new = [l for l in txt2.splitlines() if l.startswith(("boot magic", "header version", "os version", "os patch level"))]
    assert hdr_old == hdr_new, f"boot header fields differ: {hdr_old} vs {hdr_new}"
    print(f"verified: only '{changed[0]}' differs ({len(entries)} entries, same order, same header fields)")
    print("size", os.path.getsize(a.out), "sha256", hashlib.sha256(open(a.out, "rb").read()).hexdigest())


if __name__ == "__main__":
    main()
