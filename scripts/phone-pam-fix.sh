#!/bin/sh
# Phone-side fix for the PAM breakage of 2026-10-19 (docs/11 section 9.10): linux-pam 1.7.1-r4 (the `apk upgrade` of 2026-10-19) no longer ships
# pam_selinux.so, but systemd-262-r2's /usr/lib/pam.d/systemd-user and systemd-run0 still say "session required pam_selinux.so", so user@10000.service
# (the UI user's systemd manager) dies "at step PAM spawning" and plasma-mobile.service cannot start. POSIX sh, run as root
# (collect-phone-state.sh --pam-fix[=undo|check] does that).
# Linux-PAM reads /etc/pam.d before /usr/lib/pam.d, so the fix is an OVERRIDE FILE, not an edit of the package-owned one and not an apk operation (no
# mkinitfs trigger, docs/06 rule 3): /etc/pam.d/<service> = the vendor file with its pam_selinux.so lines changed from "session required" to
# "-session optional" ("-" = ignore a missing module). Each override carries a marker line; undo removes only files that carry it.
#   apply (default)  create the overrides (only when pam_selinux.so really is missing, only where no foreign override exists), then start
#                    user@UID.service once (reset-failed + start; never stop/restart) and report whether it is active
#   check            show what apply would do and write nothing
#   undo             remove the overrides that carry the marker
# Env (PC-side test): ROOT SYSTEMCTL UI_UID VERIFY (default 1) SERVICES (default "systemd-user systemd-run0")
ROOT="${ROOT:-}"
SYSTEMCTL="${SYSTEMCTL:-systemctl}"
UI_UID="${UI_UID:-10000}"
VERIFY="${VERIFY:-1}"
SERVICES="${SERVICES:-systemd-user systemd-run0}"
MARK="# dm1q-pam-fix: generated by scripts/phone-pam-fix.sh"
VENDOR="$ROOT/usr/lib/pam.d"
ETC="$ROOT/etc/pam.d"

MODE="${1:-apply}"
case "$MODE" in apply|check|undo) ;; *) sed -n '2,16p' "$0"; exit 2 ;; esac
say() { echo; echo "== $*"; }
refuse() { echo "REFUSING: $*"; exit 3; }

have_module() { [ -e "$ROOT/usr/lib/security/pam_selinux.so" ] || [ -e "$ROOT/lib/security/pam_selinux.so" ]; }

transform() { # $1 vendor file -> stdout: marker line + the file with pam_selinux lines optional
	echo "$MARK from /usr/lib/pam.d/$(basename "$1"): pam_selinux.so made optional because it is not installed (linux-pam 1.7.1-r4). Delete this file to undo."
	sed 's/^session\([[:space:]][[:space:]]*\)required\([[:space:]][[:space:]]*pam_selinux\.so\)/-session\1optional\2/' "$1"
}

if [ "$MODE" = undo ]; then
	say "undo"
	for s in $SERVICES; do
		f="$ETC/$s"
		if [ -f "$f" ] && head -n 1 "$f" | grep -q "^$MARK"; then
			rm -f "$f" && echo "removed $f"
		elif [ -e "$f" ]; then
			echo "kept $f (no marker: not ours)"
		else
			echo "$f: absent"
		fi
	done
	echo; echo "done"
	exit 0
fi

[ "${ID_U:-$(id -u)}" = 0 ] || { echo "run as root"; exit 2; }
say "preflight"
if have_module; then refuse "pam_selinux.so exists on this system: the breakage is something else, nothing to override"; fi
echo "pam_selinux.so: absent (as in the breakage)"
todo=""
for s in $SERVICES; do
	v="$VENDOR/$s"
	f="$ETC/$s"
	if [ ! -f "$v" ]; then echo "$s: no vendor file $v, skipped"; continue; fi
	if ! grep -q '^session[[:space:]][[:space:]]*required[[:space:]][[:space:]]*pam_selinux\.so' "$v"; then echo "$s: vendor file has no required pam_selinux line, skipped"; continue; fi
	if [ -e "$f" ] && ! head -n 1 "$f" | grep -q "^$MARK"; then refuse "$f exists and is not ours: not overwriting it"; fi
	todo="$todo $s"
done
[ -n "$todo" ] || { echo "nothing to do"; echo; echo "done"; exit 0; }

say "$MODE: overrides for$todo"
for s in $todo; do
	v="$VENDOR/$s"
	f="$ETC/$s"
	new=$(transform "$v")
	if [ "$MODE" = check ]; then
		echo "-- would write $f; lines that differ from the vendor file:"
		echo "$new" | sed 1d | diff "$v" - | sed 's/^/   /'
		continue
	fi
	mkdir -p "$ETC" || refuse "cannot create $ETC"
	echo "$new" > "$f.new" && chmod 644 "$f.new" && mv "$f.new" "$f" || refuse "could not write $f"
	echo "wrote $f"
	diff "$v" "$f" | sed 's/^/   /'
done

if [ "$MODE" = apply ] && [ "$VERIFY" = 1 ]; then
	say "verify: start user@$UI_UID.service once (no stop, no restart)"
	"$SYSTEMCTL" reset-failed "user@$UI_UID.service" 2>&1 | sed 's/^/  /'
	"$SYSTEMCTL" start "user@$UI_UID.service" 2>&1 | sed 's/^/  /'
	state=$("$SYSTEMCTL" is-active "user@$UI_UID.service" 2>&1)
	echo "user@$UI_UID.service: $state"
	if [ "$state" = active ]; then echo "RESULT: the UI user's systemd manager starts again"; else echo "RESULT: still not active: read the journal (collect --pam)"; fi
fi
echo
echo "done"
