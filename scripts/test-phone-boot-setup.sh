#!/usr/bin/env bash
# PC-side test of scripts/phone-boot-setup.sh (docs/06 rule 3). A fake root (firmware dir, /var, /etc/systemd/system, /boot/initramfs-extra, the
# staged firmware set), a systemctl stub that logs every call and keeps enable/default-target state, a dmesg stub, and an apk TRIPWIRE (the script must
# never call apk). Checks, per mode: the files and their hashes/modes, the manifest, the generated guard / ok / wait scripts AND their behaviour when
# actually run (first boot leaves the marker, a second boot with the marker moves the firmware away, the ok script clears the marker), the units and the
# drop-in, systemctl calls (only daemon-reload / enable / disable / get-default / set-default / is-enabled: never start, stop, restart, mask, isolate),
# idempotence, `check` writes nothing, undo removes only what is ours, all refusals, and that initramfs-extra is never touched.
# Run with dash (skipped when not installed) and bash. Usage: bash scripts/test-phone-boot-setup.sh
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
SCRIPT="$HERE/phone-boot-setup.sh"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
fail=0
ok()  { echo "  ok    $1"; }
bad() { echo "  FAIL  $1"; fail=1; }
expect() { if grep -qE -- "$3" "$1"; then ok "$2"; else bad "$2 (no match for: $3)"; fi; }

FW="qcom/a740_sqe.fw qcom/gmu_gen70200.bin qcom/sm8550/a740_zap.mbn"
mk() { # $1 = dir
	local D="$1"; rm -rf "$D"
	mkdir -p "$D/bin" "$D/src/qcom/sm8550" "$D/lib/firmware/postmarketos" "$D/sys/module/firmware_class/parameters" "$D/boot" "$D/en" \
		"$D/usr/lib/systemd/system" "$D/etc/pam.d" "$D/etc/systemd/system"
	echo /lib/firmware/postmarketos > "$D/sys/module/firmware_class/parameters/path"
	printf 'sqe-fake-content\n' > "$D/src/qcom/a740_sqe.fw"
	printf 'gmu-fake-content\n' > "$D/src/qcom/gmu_gen70200.bin"
	printf 'zap-fake-vendor-content\n' > "$D/src/qcom/sm8550/a740_zap.mbn"
	printf 'initramfs-extra-fake\n' > "$D/boot/initramfs-extra"
	printf '[Unit]\nDescription=fake plasma-mobile\n' > "$D/usr/lib/systemd/system/plasma-mobile.service"
	printf '# dm1q-pam-fix: generated by scripts/phone-pam-fix.sh\nsession optional pam_systemd.so\n' > "$D/etc/pam.d/systemd-user"
	echo multi-user.target > "$D/default"
	printf '[    7.1] [drm] Initialized msm 1.13.0\n[  7.9] msm_dpu ae01000.display-controller: [drm:adreno_request_fw [msm]] loaded qcom/a740_sqe.fw from new location\n[  8.0] [drm] Loaded GMU firmware v4.1.9\n' > "$D/dmesg"
	cat > "$D/bin/systemctl" <<EOF
#!/bin/sh
echo "systemctl \$*" >> "$D/systemctl.log"
case "\$1" in
get-default) cat "$D/default" ;;
set-default) echo "\$2" > "$D/default" ;;
is-enabled) if [ -e "$D/en/\$2" ]; then echo enabled; else echo disabled; exit 1; fi ;;
enable) shift; for u in "\$@"; do touch "$D/en/\$u"; done ;;
disable) shift; for u in "\$@"; do rm -f "$D/en/\$u"; done ;;
esac
exit 0
EOF
	cat > "$D/bin/dmesg" <<EOF
#!/bin/sh
cat "$D/dmesg"
EOF
	cat > "$D/bin/apk" <<EOF
#!/bin/sh
echo "apk \$*" >> "$D/apk.log"
exit 1
EOF
	chmod +x "$D/bin/systemctl" "$D/bin/dmesg" "$D/bin/apk"
}
sha() { sha256sum "$1" | cut -d' ' -f1; }
tree() { (cd "$1" && find . -type f -not -name systemctl.log -not -name apk.log -not -name out -not -name kmsg -exec cksum {} + | sort; ls "$1/en" | sort; cat "$1/default"); }
run() { # $1 shell $2 dir, rest args
	local sh="$1" D="$2"; shift 2
	timeout 60 env ROOT="$D" SYSFS="$D/sys" SYSTEMCTL="$D/bin/systemctl" DMESG="$D/bin/dmesg" SRC="$D/src" ID_U="${ID_U_T-0}" \
		FW_SQE_SHA="${PIN_SQE:-$(sha "$D/src/qcom/a740_sqe.fw")}" FW_GMU_SHA="${PIN_GMU:-$(sha "$D/src/qcom/gmu_gen70200.bin")}" \
		FW_ZAP_SHA="${PIN_ZAP:-$(sha "$D/src/qcom/sm8550/a740_zap.mbn")}" FORCE_GPU_UNPROVEN="${FORCE_T:-0}" \
		PATH="$D/bin:$PATH" "$sh" "$SCRIPT" "$@" > "$D/out" 2>&1
}
forbidden() { grep -E '^systemctl (start|stop|restart|try-restart|mask|unmask|isolate|reboot|poweroff|kill|reset-failed)' "$1/systemctl.log" 2>/dev/null; }

for sh in dash bash; do
	command -v "$sh" >/dev/null || { echo "skip $sh (not installed)"; continue; }

	echo "== $sh: gpu-fw apply"
	D="$W/a-$sh"; mk "$D"; extra=$(cksum < "$D/boot/initramfs-extra")
	run "$sh" "$D" gpu-fw; rc=$?; O="$D/out"
	[ "$rc" = 0 ] && ok "exit 0" || { bad "exit $rc"; cat "$O"; }
	for rel in $FW; do
		d="$D/lib/firmware/postmarketos/$rel"
		[ -f "$d" ] && cmp -s "$d" "$D/src/$rel" && ok "$rel installed, same bytes" || bad "$rel missing or different"
		[ "$(stat -c %a "$d" 2>/dev/null)" = 644 ] && ok "$rel mode 644" || bad "$rel mode $(stat -c %a "$d" 2>/dev/null)"
		grep -qx "$(sha "$D/src/$rel") /lib/firmware/postmarketos/$rel" "$D/var/lib/dm1q/gpu-fw.manifest" && ok "manifest line for $rel (real path, no test prefix)" || bad "manifest line for $rel"
	done
	[ "$(wc -l < "$D/var/lib/dm1q/gpu-fw.manifest")" = 3 ] && ok "manifest has exactly 3 lines" || bad "manifest line count"
	for f in usr/local/sbin/dm1q-gpu-fw-guard usr/local/sbin/dm1q-gpu-fw-ok; do [ -x "$D/$f" ] && ok "$f executable" || bad "$f not executable"; done
	for f in etc/systemd/system/dm1q-gpu-fw-guard.service etc/systemd/system/dm1q-gpu-fw-ok.service; do
		[ -f "$D/$f" ] && head -n 1 "$D/$f" | grep -q '^# dm1q-boot-setup' && ok "$f written with the marker" || bad "$f missing or no marker"
	done
	expect "$D/etc/systemd/system/dm1q-gpu-fw-guard.service" "guard unit runs before udev and sysinit" "^Before=systemd-udev-trigger.service .*sysinit.target"
	expect "$D/etc/systemd/system/dm1q-gpu-fw-guard.service" "guard unit is WantedBy sysinit" "^WantedBy=sysinit.target"
	expect "$D/etc/systemd/system/dm1q-gpu-fw-guard.service" "guard unit stays active so that ExecStop runs at shutdown" "^RemainAfterExit=yes"
	expect "$D/etc/systemd/system/dm1q-gpu-fw-guard.service" "guard unit clears the marker at a clean shutdown" "^ExecStop=/usr/local/sbin/dm1q-gpu-fw-clean"
	[ -x "$D/usr/local/sbin/dm1q-gpu-fw-clean" ] && ok "clean script executable" || bad "clean script missing"
	expect "$D/etc/systemd/system/dm1q-gpu-fw-ok.service" "ok unit starts after multi-user" "^After=multi-user.target"
	expect "$D/etc/systemd/system/dm1q-gpu-fw-ok.service" "ok unit points at the ok script" "^ExecStart=/usr/local/sbin/dm1q-gpu-fw-ok"
	[ ! -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && ok "no marker at install time" || bad "marker created at install time"
	grep -qx 'systemctl daemon-reload' "$D/systemctl.log" && ok "daemon-reload" || bad "no daemon-reload"
	grep -qx 'systemctl enable dm1q-gpu-fw-guard.service dm1q-gpu-fw-ok.service' "$D/systemctl.log" && ok "both units enabled" || bad "units not enabled"
	[ -z "$(forbidden "$D")" ] && ok "no start / stop / restart / mask / isolate" || bad "forbidden systemctl call: $(forbidden "$D")"
	[ ! -e "$D/apk.log" ] && ok "apk never called" || bad "apk was called: $(cat "$D/apk.log")"
	[ "$extra" = "$(cksum < "$D/boot/initramfs-extra")" ] && ok "initramfs-extra untouched" || bad "initramfs-extra changed"
	expect "$O" "says initramfs-extra unchanged" "^initramfs-extra unchanged"
	expect "$O" "result line" "^RESULT: GPU firmware installed under /lib/firmware/postmarketos"
	[ ! -e "$D/etc/systemd/system/plasma-mobile.service.d" ] && ok "gpu-fw does not touch the Plasma unit" || bad "gpu-fw created a Plasma drop-in"
	after1=$(tree "$D")
	run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 0 ] && [ "$after1" = "$(tree "$D")" ] && ok "idempotent: second gpu-fw changes nothing" || bad "second gpu-fw changed files (rc $rc)"

	echo "== $sh: the generated guard, run for real"
	G="$D/usr/local/sbin/dm1q-gpu-fw-guard"
	runguard() { DM1Q_ROOT="$D" DM1Q_KMSG="$D/kmsg" timeout 20 "$sh" "$G"; }
	runguard; rc=$?
	[ "$rc" = 0 ] && ok "guard exit 0" || bad "guard exit $rc"
	[ -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && ok "first boot: marker created" || bad "first boot: no marker"
	[ -f "$D/lib/firmware/postmarketos/qcom/sm8550/a740_zap.mbn" ] && ok "first boot: firmware stays" || bad "first boot: firmware removed"
	DM1Q_ROOT="$D" DM1Q_OK_DELAY=0 timeout 20 "$sh" "$D/usr/local/sbin/dm1q-gpu-fw-ok"
	[ ! -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && ok "ok script clears the marker" || bad "ok script left the marker"
	runguard; runguard; rc=$?
	[ "$rc" = 0 ] && ok "guard exit 0 on the breaking boot" || bad "guard exit $rc"
	for rel in $FW; do [ ! -e "$D/lib/firmware/postmarketos/$rel" ] && ok "marker found: $rel moved away" || bad "marker found: $rel still installed"; done
	for b in a740_sqe.fw gmu_gen70200.bin a740_zap.mbn; do [ -f "$D/var/lib/dm1q/gpu-fw-disabled/$b" ] && ok "$b kept in gpu-fw-disabled" || bad "$b not kept"; done
	[ ! -e "$D/var/lib/dm1q/gpu-fw.manifest" ] && [ -f "$D/var/lib/dm1q/gpu-fw-disabled/gpu-fw.manifest.disabled" ] && ok "manifest renamed" || bad "manifest not renamed"
	[ ! -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && ok "marker removed by the guard" || bad "marker left after the breaking boot"
	expect "$D/kmsg" "kernel log line written" "dm1q-gpu-fw-guard: the previous boot did not finish"
	runguard; rc=$?
	[ "$rc" = 0 ] && [ ! -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && ok "no manifest: guard does nothing" || bad "guard acted without a manifest"
	echo "-- a clean shutdown (the ExecStop script) protects a quick reboot"
	run "$sh" "$D" gpu-fw >/dev/null 2>&1
	runguard
	[ -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && ok "boot 1: marker left" || bad "boot 1: no marker"
	DM1Q_ROOT="$D" timeout 20 "$sh" "$D/usr/local/sbin/dm1q-gpu-fw-clean"; rc=$?
	[ "$rc" = 0 ] && [ ! -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && ok "clean shutdown clears the marker" || bad "clean script left the marker (rc $rc)"
	runguard
	[ -f "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw" ] && [ -e "$D/var/lib/dm1q/gpu-fw-boot-pending" ] && [ ! -d "$D/var/lib/dm1q/gpu-fw-disabled" ] && ok "boot 2 after a clean reboot: firmware stays, new marker" || bad "a clean reboot still disabled the firmware"
	runguard
	[ ! -f "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw" ] && ok "boot 3 after NO clean shutdown: firmware moved away" || bad "an unclean end did not trip the guard"
	echo "-- check after the guard acted"
	run "$sh" "$D" check; expect "$D/out" "check reports disabled-by-guard" "^gpu_fw=disabled-by-guard"
	run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 0 ] && [ -f "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw" ] && [ ! -d "$D/var/lib/dm1q/gpu-fw-disabled" ] && ok "gpu-fw again puts the firmware back and clears the disabled dir" || bad "re-install after the guard failed (rc $rc)"

	echo "== $sh: the generated wait script"
	W2="$D/usr/local/sbin/dm1q-plasma-gate"
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 0 ] && [ -x "$W2" ] && ok "plasma wrote an executable wait script" || { bad "wait script (rc $rc)"; cat "$D/out"; }
	touch "$D/node"
	gate() { DM1Q_ROOT="$D" DM1Q_DMESG="$D/bin/dmesg" DM1Q_KMSG="$D/kmsg" DM1Q_GPU_TRIES=1 DM1Q_RENDER_NODE="${NODE:-$D/node}" DM1Q_WAIT_TRIES=2 timeout 20 "$sh" "$W2" 2>"$D/gate-err"; }
	gate; rc=$?
	[ "$rc" = 0 ] && ok "gate: node present and GPU initialised: exit 0" || bad "gate rc $rc"
	NODE="$D/nonode" gate; rc=$?
	[ "$rc" = 0 ] && ok "gate: no render node but GPU initialised: still exit 0 (the node wait never fails)" || bad "gate rc $rc"
	cp "$D/dmesg" "$D/dmesg.good"
	printf '[  7.1] [drm] Initialized msm 1.13.0\n[  7.9] msm_dpu: Direct firmware load for qcom/a740_sqe.fw failed with error -2\n' > "$D/dmesg"
	: > "$D/kmsg"; gate; rc=$?
	[ "$rc" = 1 ] && ok "gate: GPU not initialised: exit 1 (Plasma does not start on llvmpipe)" || bad "gate rc $rc (expected 1)"
	expect "$D/kmsg" "gate: kernel log line" "dm1q-plasma-gate: the GPU did not initialise"
	expect "$D/gate-err" "gate: message on stderr (journal)" "not starting Plasma"
	printf '[  8.0] [drm] Loaded GMU firmware v4.1.9\n[  8.1] msm_dpu: [drm:adreno_load_gpu] gpu hw init failed: -22\n' > "$D/dmesg"
	gate; rc=$?
	[ "$rc" = 1 ] && ok "gate: GMU line but a hw init failure: exit 1" || bad "gate rc $rc (expected 1)"
	mkdir -p "$D/var/lib/dm1q"; touch "$D/var/lib/dm1q/plasma-allow-cpu"
	gate; rc=$?
	[ "$rc" = 0 ] && ok "gate: plasma-allow-cpu escape hatch lets it through" || bad "gate rc $rc with the escape hatch"
	rm -f "$D/var/lib/dm1q/plasma-allow-cpu"; cp "$D/dmesg.good" "$D/dmesg"

	echo "== $sh: check writes nothing"
	D="$W/c-$sh"; mk "$D"; run "$sh" "$D" gpu-fw; b=$(tree "$D")
	run "$sh" "$D" check; rc=$?
	[ "$rc" = 0 ] && [ "$b" = "$(tree "$D")" ] && ok "check: nothing written" || bad "check changed something (rc $rc)"
	expect "$D/out" "gpu_fw=installed" "^gpu_fw=installed"
	expect "$D/out" "gpu_state=initialised" "^gpu_state=initialised"
	expect "$D/out" "plasma_boot=disabled" "^plasma_boot=disabled"
	expect "$D/out" "PAM ok line" "^PAM: ok"
	[ -z "$(forbidden "$D")" ] && ok "check: no mutating systemctl call" || bad "check called: $(forbidden "$D")"
	D="$W/c2-$sh"; mk "$D"; run "$sh" "$D" check
	expect "$D/out" "fresh phone: gpu_fw=absent" "^gpu_fw=absent"

	echo "== $sh: undo-gpu-fw"
	D="$W/d-$sh"; mk "$D"; run "$sh" "$D" gpu-fw
	printf 'changed\n' > "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw"
	printf 'my unit\n' > "$D/etc/systemd/system/dm1q-gpu-fw-ok.service"
	run "$sh" "$D" undo-gpu-fw; rc=$?
	[ "$rc" = 0 ] && ok "undo exit 0" || bad "undo exit $rc"
	[ ! -e "$D/lib/firmware/postmarketos/qcom/gmu_gen70200.bin" ] && [ ! -e "$D/lib/firmware/postmarketos/qcom/sm8550/a740_zap.mbn" ] && ok "matching firmware removed" || bad "firmware still there"
	[ "$(cat "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw")" = changed ] && ok "a file that no longer matches the manifest is kept" || bad "changed firmware removed"
	expect "$D/out" "kept message" "kept .*a740_sqe.fw \\(content differs"
	[ ! -e "$D/etc/systemd/system/dm1q-gpu-fw-guard.service" ] && ok "our guard unit removed" || bad "guard unit left"
	[ "$(cat "$D/etc/systemd/system/dm1q-gpu-fw-ok.service")" = "my unit" ] && ok "a unit without the marker is kept" || bad "foreign unit removed"
	[ ! -e "$D/usr/local/sbin/dm1q-gpu-fw-guard" ] && [ ! -e "$D/usr/local/sbin/dm1q-gpu-fw-clean" ] && [ ! -e "$D/var/lib/dm1q/gpu-fw.manifest" ] && ok "guard and clean scripts and manifest removed" || bad "leftovers"
	grep -qx 'systemctl disable dm1q-gpu-fw-guard.service dm1q-gpu-fw-ok.service' "$D/systemctl.log" && ok "units disabled" || bad "units not disabled"

	echo "== $sh: gpu-fw refusals"
	D="$W/e1-$sh"; mk "$D"; pin=$(sha "$D/src/qcom/sm8550/a740_zap.mbn"); printf 'tampered\n' > "$D/src/qcom/sm8550/a740_zap.mbn"
	PIN_ZAP="$pin" run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 3 ] && ok "hash mismatch: exit 3" || bad "hash mismatch: exit $rc"
	expect "$D/out" "reason" "is not the pinned"
	[ ! -e "$D/lib/firmware/postmarketos/qcom" ] && [ ! -e "$D/var/lib/dm1q" ] && ok "nothing written on a hash mismatch" || bad "wrote files despite the mismatch"
	D="$W/e2-$sh"; mk "$D"
	PIN_ZAP=386bbdc25ae94a9398e33e7580eecfdcef6c472682a1e3123e1374bcffe7cde3 run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 3 ] && ok "generic zap pin: exit 3" || bad "generic zap pin: exit $rc"
	expect "$D/out" "reason" "generic linux-firmware zap shader is refused"
	D="$W/e3-$sh"; mk "$D"; echo /lib/firmware > "$D/sys/module/firmware_class/parameters/path"
	run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 3 ] && ok "wrong firmware_class.path: exit 3" || bad "wrong firmware_class.path: exit $rc"
	expect "$D/out" "reason" "REFUSING: firmware_class.path is '/lib/firmware'"
	D="$W/e4-$sh"; mk "$D"; mkdir -p "$D/lib/firmware/postmarketos/qcom"; printf 'foreign\n' > "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw"
	run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 3 ] && ok "foreign file in place: exit 3" || bad "foreign file: exit $rc"
	[ "$(cat "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw")" = foreign ] && ok "foreign file untouched" || bad "foreign file overwritten"
	D="$W/e5-$sh"; mk "$D"; rm "$D/src/qcom/gmu_gen70200.bin"
	PIN_GMU=0000 run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 3 ] && ok "missing staged file: exit 3" || bad "missing staged file: exit $rc"
	D="$W/e6-$sh"; mk "$D"
	ID_U_T=1 run "$sh" "$D" gpu-fw; rc=$?
	[ "$rc" = 2 ] && ok "not root: exit 2" || bad "not root: exit $rc"
	D="$W/e7-$sh"; mk "$D"
	run "$sh" "$D" bogus; rc=$?
	[ "$rc" = 2 ] && ok "bad mode: exit 2" || bad "bad mode: exit $rc"

	echo "== $sh: plasma"
	D="$W/p1-$sh"; mk "$D"
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 3 ] && ok "no GPU firmware: exit 3" || bad "no GPU firmware: exit $rc"
	expect "$D/out" "reason" "REFUSING: the GPU firmware is not installed"
	[ ! -e "$D/etc/systemd/system/plasma-mobile.service.d" ] && [ ! -s "$D/systemctl.log" ] && ok "refusal wrote and called nothing" || bad "refusal changed something"
	D="$W/p2-$sh"; mk "$D"; run "$sh" "$D" gpu-fw; printf '[  7.1] [drm] Initialized msm\n[  7.2] msm_dpu: no GPU device was found\n' > "$D/dmesg"
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 3 ] && ok "GPU not initialised in this boot: exit 3" || bad "GPU not initialised: exit $rc"
	expect "$D/out" "reason" "the GPU did not initialise by itself"
	FORCE_T=1 run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 0 ] && ok "FORCE_GPU_UNPROVEN=1 lets it through" || bad "force: exit $rc"
	D="$W/p3-$sh"; mk "$D"; run "$sh" "$D" gpu-fw; printf '[  8.0] [drm] Loaded GMU firmware v4.1.9\n[  8.1] msm_dpu: [drm:adreno_load_gpu] gpu hw init failed: -22\n' >> "$D/dmesg"
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 3 ] && ok "a hw init failure line after the GMU line: exit 3" || bad "failure line ignored: exit $rc"
	D="$W/p4-$sh"; mk "$D"; run "$sh" "$D" gpu-fw; rm "$D/etc/pam.d/systemd-user"
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 3 ] && ok "PAM not solved: exit 3" || bad "PAM: exit $rc"
	expect "$D/out" "reason" "REFUSING: the PAM breakage"
	mkdir -p "$D/usr/lib/security"; touch "$D/usr/lib/security/pam_selinux.so"
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 0 ] && ok "pam_selinux.so present is enough" || bad "module present: exit $rc"
	D="$W/p5-$sh"; mk "$D"; run "$sh" "$D" gpu-fw; : > "$D/systemctl.log"
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 0 ] && ok "exit 0" || { bad "exit $rc"; cat "$D/out"; }
	DR="$D/etc/systemd/system/plasma-mobile.service.d/10-dm1q-boot.conf"
	[ -f "$DR" ] && head -n 1 "$DR" | grep -q '^# dm1q-boot-setup' && ok "drop-in written with the marker" || bad "drop-in missing"
	expect "$DR" "drop-in limits the restart loop" "^StartLimitBurst=4"
	expect "$DR" "drop-in has the interval" "^StartLimitIntervalSec=180"
	expect "$DR" "drop-in waits for the render node" "^ExecStartPre=/usr/local/sbin/dm1q-plasma-gate"
	grep -qx 'systemctl enable plasma-mobile.service' "$D/systemctl.log" && ok "enable plasma-mobile.service" || bad "no enable"
	grep -qx 'systemctl set-default graphical.target' "$D/systemctl.log" && ok "default target set to graphical" || bad "no set-default"
	[ "$(cat "$D/var/lib/dm1q/plasma-prev-default")" = multi-user.target ] && ok "previous default recorded" || bad "previous default not recorded"
	[ -z "$(forbidden "$D")" ] && ok "never start / stop / restart / isolate" || bad "forbidden systemctl call: $(forbidden "$D")"
	[ ! -e "$D/apk.log" ] && ok "apk never called" || bad "apk was called"
	expect "$D/out" "result line" "^RESULT: plasma-mobile.service starts at every boot"
	after1=$(tree "$D")
	run "$sh" "$D" plasma; rc=$?
	[ "$rc" = 0 ] && [ "$after1" = "$(tree "$D")" ] && ok "idempotent: second plasma changes nothing" || bad "second plasma changed files (rc $rc)"
	[ "$(cat "$D/var/lib/dm1q/plasma-prev-default")" = multi-user.target ] && ok "second run keeps the ORIGINAL previous default" || bad "previous default overwritten: $(cat "$D/var/lib/dm1q/plasma-prev-default")"
	D="$W/p6-$sh"; mk "$D"; echo graphical.target > "$D/default"; run "$sh" "$D" gpu-fw; : > "$D/systemctl.log"; run "$sh" "$D" plasma
	grep -q 'set-default' "$D/systemctl.log" && bad "set-default called although the default is already graphical" || ok "already graphical: no set-default"
	[ ! -e "$D/var/lib/dm1q/plasma-prev-default" ] && ok "already graphical: nothing to remember" || bad "stray prev-default"

	echo "== $sh: undo-plasma"
