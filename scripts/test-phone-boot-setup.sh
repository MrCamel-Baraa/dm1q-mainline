	[ ! -e "$D/en/plasma-mobile.service" ] && ok "plasma-mobile.service disabled" || bad "still enabled"
	[ -f "$D/lib/firmware/postmarketos/qcom/a740_sqe.fw" ] && ok "GPU firmware untouched by undo-plasma" || bad "undo-plasma removed the firmware"
	[ -z "$(forbidden "$D")" ] && ok "undo never stops the running UI" || bad "forbidden: $(forbidden "$D")"
	D="$W/u2-$sh"; mk "$D"; run "$sh" "$D" gpu-fw; run "$sh" "$D" plasma
	printf 'foreign\n' > "$D/etc/systemd/system/plasma-mobile.service.d/10-dm1q-boot.conf"
	run "$sh" "$D" undo-plasma
	[ "$(cat "$D/etc/systemd/system/plasma-mobile.service.d/10-dm1q-boot.conf")" = foreign ] && ok "a drop-in without the marker is kept" || bad "foreign drop-in removed"
