#!/usr/bin/env bash
# PC-side test of scripts/phone-pam-fix.sh (docs/06 rule 3). A fake root with the vendor systemd-user / systemd-run0 PAM files (pam_selinux.so required,
# module missing), a systemctl stub that logs its calls. Checks: apply writes override files that differ from the vendor ones ONLY in the pam_selinux lines
# ("-session ... optional"), marker line present, vendor files untouched, idempotent, `check` writes nothing, undo removes only marked files, refusals
# (module exists, foreign override, not root), verification only ever calls reset-failed / start / is-active (never stop / restart / kill), nothing else is
# touched. Run with dash (skipped when not installed) and bash. Usage: bash scripts/test-phone-pam-fix.sh
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
fail=0
ok()  { echo "  ok    $1"; }
bad() { echo "  FAIL  $1"; fail=1; }
expect() { if grep -qE -- "$3" "$1"; then ok "$2"; else bad "$2 (no match for: $3)"; fi; }
reject() { if grep -qE -- "$3" "$1"; then bad "$2 (unexpected: $3)"; else ok "$2"; fi; }

mk() { # $1 = dir
	local D="$1"; rm -rf "$D"
	mkdir -p "$D/usr/lib/pam.d" "$D/etc/pam.d" "$D/usr/lib/security" "$D/bin"
	# the real systemd-user file of systemd-262-r2 (docs/11 9.10), run0 has the same two lines
	cat > "$D/usr/lib/pam.d/systemd-user" <<'EOF'
# SPDX-License-Identifier: LGPL-2.1-or-later
# Used by systemd --user instances.

account  required   pam_unix.so no_pass_expiry
auth     required   pam_rootok.so

session  required   pam_selinux.so close
session  required   pam_selinux.so nottys open
session  required   pam_loginuid.so
session  optional   pam_keyinit.so force revoke
session  required   pam_namespace.so
session  optional   pam_umask.so silent
session  optional   pam_systemd.so
EOF
	cat > "$D/usr/lib/pam.d/systemd-run0" <<'EOF'
auth     required   pam_rootok.so
session  required   pam_selinux.so close
session  required   pam_selinux.so open
session  required   pam_loginuid.so
EOF
	touch "$D/usr/lib/security/pam_unix.so" "$D/usr/lib/security/pam_loginuid.so"
	cat > "$D/bin/systemctl" <<EOF
#!/bin/sh
echo "systemctl \$*" >> "$D/systemctl.log"
case "\$1" in is-active) cat "$D/state" 2>/dev/null || echo failed ;; esac
exit 0
EOF
	chmod +x "$D/bin/systemctl"
	echo active > "$D/state"
}
tree() { (cd "$1" && find . -type f -not -name systemctl.log -not -name state -not -name out -exec cksum {} + | sort); }
run() { # $1 shell $2 dir, rest args
	local sh="$1" D="$2"; shift 2
	timeout 20 env ROOT="$D" SYSTEMCTL="$D/bin/systemctl" ID_U="${ID_U_T-0}" "$sh" "$HERE/phone-pam-fix.sh" "$@" > "$D/out" 2>&1
}

for sh in dash bash; do
	command -v "$sh" >/dev/null || { echo "skip $sh (not installed)"; continue; }
	echo "== $sh: apply"
	D="$W/a-$sh"; mk "$D"; vend=$(cd "$D/usr/lib/pam.d" && cksum systemd-user systemd-run0)
	run "$sh" "$D"; rc=$?; O="$D/out"
	[ "$rc" = 0 ] && ok "exit 0" || { bad "exit $rc"; cat "$O"; }
	for s in systemd-user systemd-run0; do
		f="$D/etc/pam.d/$s"
		[ -f "$f" ] && ok "$s override written" || bad "$s override missing"
		head -n 1 "$f" | grep -q '^# dm1q-pam-fix: generated by' && ok "$s marker line" || bad "$s marker missing"
		sed 1d "$f" | grep -c 'pam_selinux' | grep -q '^[12]$' && ok "$s keeps the selinux lines (marker excluded)" || bad "$s selinux lines count"
		grep -q '^session .*required.*pam_selinux' "$f" && bad "$s still has a required pam_selinux line" || ok "$s no required pam_selinux line left"
		grep -q '^-session  *optional  *pam_selinux\.so' "$f" && ok "$s selinux lines are '-session ... optional'" || bad "$s transformed lines wrong"
		# everything else identical to the vendor file
		diff <(grep -v 'pam_selinux' "$D/usr/lib/pam.d/$s") <(sed 1d "$f" | grep -v 'pam_selinux') >/dev/null && ok "$s: all non-selinux lines identical to the vendor file" || bad "$s differs elsewhere"
	done
	grep -q 'nottys open' "$D/etc/pam.d/systemd-user" && ok "the 'nottys open' argument survives" || bad "arguments lost"
	[ "$vend" = "$(cd "$D/usr/lib/pam.d" && cksum systemd-user systemd-run0)" ] && ok "vendor files untouched" || bad "vendor files changed"
	grep -qx 'systemctl reset-failed user@10000.service' "$D/systemctl.log" && ok "reset-failed called" || bad "no reset-failed"
	grep -qx 'systemctl start user@10000.service' "$D/systemctl.log" && ok "start called" || bad "no start"
	grep -qE 'stop|restart|kill|disable|mask|daemon-reload' "$D/systemctl.log" && bad "forbidden systemctl call: $(cat "$D/systemctl.log")" || ok "only reset-failed / start / is-active"
	expect "$O" "result line" "^RESULT: the UI user's systemd manager starts again"
	[ -z "$(ls "$D/etc/pam.d" | grep -v -e '^systemd-user$' -e '^systemd-run0$')" ] && ok "nothing else created in /etc/pam.d" || bad "stray files: $(ls "$D/etc/pam.d")"
	after1=$(tree "$D")
	run "$sh" "$D"; rc=$?
	[ "$rc" = 0 ] && [ "$after1" = "$(tree "$D")" ] && ok "idempotent: second apply changes nothing" || bad "second apply changed files (rc $rc)"

	echo "== $sh: still failing after apply"
	D="$W/b-$sh"; mk "$D"; echo failed > "$D/state"
	run "$sh" "$D"; expect "$D/out" "inactive manager reported" "^RESULT: still not active"

	echo "== $sh: check writes nothing"
	D="$W/c-$sh"; mk "$D"; b=$(tree "$D")
	run "$sh" "$D" check; rc=$?
	[ "$rc" = 0 ] && [ "$b" = "$(tree "$D")" ] && ok "check: no file written" || bad "check changed something (rc $rc)"
	[ ! -e "$D/systemctl.log" ] && ok "check: systemctl not called" || bad "check called systemctl"
	expect "$D/out" "check shows the would-be diff" "would write .*systemd-user"
	expect "$D/out" "diff mentions the optional line" "-session +optional +pam_selinux\\.so close"

	echo "== $sh: undo"
	D="$W/d-$sh"; mk "$D"; run "$sh" "$D"
	printf 'my own\n' > "$D/etc/pam.d/systemd-run0"
	run "$sh" "$D" undo; rc=$?
	[ "$rc" = 0 ] && ok "undo exit 0" || bad "undo exit $rc"
	[ ! -e "$D/etc/pam.d/systemd-user" ] && ok "our override removed" || bad "override still there"
	[ "$(cat "$D/etc/pam.d/systemd-run0")" = "my own" ] && ok "a file without the marker is kept" || bad "foreign file removed"
	expect "$D/out" "kept message" "kept .*systemd-run0 \\(no marker"

	echo "== $sh: refusals"
	D="$W/e-$sh"; mk "$D"; touch "$D/usr/lib/security/pam_selinux.so"
	run "$sh" "$D"; rc=$?
	[ "$rc" = 3 ] && ok "module present: exit 3" || bad "module present: exit $rc"
	expect "$D/out" "reason" "REFUSING: pam_selinux\\.so exists"
	[ -z "$(ls "$D/etc/pam.d")" ] && ok "nothing written when the module exists" || bad "wrote files despite the module"
	D="$W/f-$sh"; mk "$D"; printf 'foreign\n' > "$D/etc/pam.d/systemd-user"
	run "$sh" "$D"; rc=$?
	[ "$rc" = 3 ] && ok "foreign override: exit 3" || bad "foreign override: exit $rc"
	[ "$(cat "$D/etc/pam.d/systemd-user")" = foreign ] && ok "foreign override untouched" || bad "foreign override overwritten"
	D="$W/g-$sh"; mk "$D"
	ID_U_T=1 run "$sh" "$D"; rc=$?
	[ "$rc" = 2 ] && ok "not root: exit 2" || bad "not root: exit $rc"
	D="$W/h-$sh"; mk "$D"
	run "$sh" "$D" bogus; rc=$?
	[ "$rc" = 2 ] && ok "bad mode: exit 2" || bad "bad mode: exit $rc"
	D="$W/i-$sh"; mk "$D"; sed -i '/pam_selinux/d' "$D/usr/lib/pam.d/systemd-user" "$D/usr/lib/pam.d/systemd-run0"
	run "$sh" "$D"; expect "$D/out" "nothing to do when the vendor files are fine" "^nothing to do"
done

echo "== static checks"
bash --posix -n "$HERE/phone-pam-fix.sh" && ok "bash --posix -n" || bad "bash --posix -n"
if command -v shellcheck >/dev/null; then
	shellcheck -s sh -S warning "$HERE/phone-pam-fix.sh" && ok "shellcheck -s sh -S warning" || bad "shellcheck"
else
	echo "  skip  shellcheck (not installed)"
fi

echo
[ "$fail" = 0 ] && echo "all tests passed" || { echo "SOME TESTS FAILED"; exit 1; }
